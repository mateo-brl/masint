// Sigles conservés en capitales par le libellé de repli, indexés en minuscules.
const ACRONYMS = new Map(
  [
    'DNS', 'MX', 'NS', 'SOA', 'TXT', 'CNAME', 'AAAA', 'CAA', 'PTR', 'SRV', 'SPF', 'DMARC', 'DKIM', 'BIMI', 'DNSSEC',
    'ASN', 'IP', 'IPs', 'IPv4', 'IPv6', 'CIDR', 'BGP', 'RIR', 'ISP', 'URL', 'URLs', 'ID', 'IDs', 'UID', 'UUID',
    'OTX', 'TLS', 'SSL', 'SAN', 'HTTP', 'HTTPS', 'CDN', 'VPN', 'API', 'HTML', 'JSON', 'XML', 'PDF', 'CSV',
    'IBAN', 'BIC', 'SEPA', 'SIREN', 'SIRET', 'NAF', 'RNA', 'TVA', 'VAT',
    'MD5', 'SHA-1', 'SHA-256', 'SHA-512', 'MMH3', 'EXIF', 'IPTC', 'GPS', 'OSM',
    'HLR', 'MCC', 'MNC', 'IMSI', 'IMEI', 'SIM', 'MAC', 'OUI', 'OS',
    'CVE', 'CVSS', 'CWE', 'CPE', 'EPSS', 'KEV', 'NVD', 'RDAP', 'WHOIS', 'IANA', 'ICANN', 'TLD', 'OFAC', 'HIBP',
    'ENS', 'NFT', 'EVM', 'BTC', 'ETH', 'TRX', 'USD', 'USDT', 'EUR', 'UTC', 'NSFW', 'FIDE', 'VAC', 'XP'
  ].map((a): [string, string] => [a.toLowerCase().replace(/-/g, ''), a])
)

const hasLabel = (key: string): boolean => Object.prototype.hasOwnProperty.call(PROPERTY_LABELS, key)

/** Libellé lisible d'une propriété : dictionnaire, sinon libellé tiré de la clé. */
export function propertyLabel(key: string, lang: 'fr' | 'en'): string {
  if (hasLabel(key)) return PROPERTY_LABELS[key][lang]
  // Total d'une liste plafonnée (`<clé>_count`, voir cappedList) dont la clé est connue.
  const list = /^(.+)_count$/.exec(key)?.[1]
  if (list && hasLabel(list)) return countLabel(PROPERTY_LABELS[list][lang], lang)
  return humanizeKey(key)
}

/** « Ports ouverts » → « Nombre de ports ouverts » ; « Tags (OTX) » → « Tags count (OTX) ». */
function countLabel(label: string, lang: 'fr' | 'en'): string {
  // En anglais le libellé commence souvent par un nom propre (GitHub, Tor) : on ne le touche pas.
  if (lang === 'en') return label.replace(/^(.*?)( \(.+\))?$/, '$1 count$2')
  const rest = /^.[a-zà-ÿ]/.test(label) ? label.charAt(0).toLowerCase() + label.slice(1) : label
  return /^[aeiouyhàâäéèêëîïôöûü]/i.test(rest) ? `Nombre d'${rest}` : `Nombre de ${rest}`
}

/** `dmarc_policy` → « DMARC policy », `lastSeenAt` → « Last seen at ». */
function humanizeKey(key: string): string {
  const words = key
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[\s_]+/)
    .filter(Boolean)
    .map((w) => ACRONYMS.get(w.toLowerCase()) ?? w.toLowerCase())
  if (!words.length) return key
  words[0] = words[0].charAt(0).toUpperCase() + words[0].slice(1)
  return words.join(' ')
}
